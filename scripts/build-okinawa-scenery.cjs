'use strict';
const fs=require('node:fs'),path=require('node:path'),{buildSync}=require('esbuild');
const {atlasPng}=require('./lib/okinawa-scenery/scenery.cjs');
const result=buildSync({
 stdin:{contents:'window.OkinawaSceneryTemplates={create:require("./lib/okinawa-scenery/templates.cjs").create,png:ATLAS};',
  resolveDir:__dirname},
 define:{ATLAS:JSON.stringify('data:image/png;base64,'+atlasPng().toString('base64'))},
 platform:'browser',external:['node:fs','node:zlib'],target:'safari15',bundle:true,minify:true,write:false,
});
const content=result.outputFiles[0].contents;
if(content.length>96*1024)throw Error('Okinawa scenery generator exceeds 96 KiB.');
fs.writeFileSync(path.resolve(__dirname,'../okinawa/coastal-templates.js'),
 Buffer.concat([Buffer.from('/* Generated by scripts/build-okinawa-scenery.cjs. Original Torpedo-Bomber scenery. */\n'),content]));
console.log('Okinawa scenery templates:',content.length,'bytes; includes one 512 x 512 albedo atlas.');
